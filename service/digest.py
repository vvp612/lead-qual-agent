"""Weekly digest: a Slack/email-ready markdown summary of the CRM rows."""
from __future__ import annotations

from collections import Counter


def weekly_digest(rows: list[dict]) -> str:
    total = len(rows)
    status = Counter(r.get("status", "?") for r in rows)
    intent = Counter(r.get("intent", "?") for r in rows)
    escalations = [r for r in rows if str(r.get("needs_human", "")).lower() in {"true", "1", "yes"}]
    top = sorted((r for r in rows if r.get("email")), key=lambda r: int(r.get("score", 0) or 0), reverse=True)[:5]

    lines = ["# ShopDesk — Weekly Lead & Support Digest", ""]
    lines.append(f"**{total}** inbound · " + " · ".join(f"{status[s]} {s}" for s in ("hot", "warm", "cold", "spam") if status[s]))
    lines.append(f"**{len(escalations)}** flagged for a human · top intents: " + ", ".join(f"{k} ({v})" for k, v in intent.most_common(3)))
    lines.append("")
    if top:
        lines.append("## Top leads")
        for r in top:
            who = r.get("customer") or r.get("email")
            lines.append(f"- **{r.get('score')}** · {r.get('status')} · {who} — _{r.get('intent')}_")
        lines.append("")
    if escalations:
        lines.append("## Needs a human")
        for r in escalations:
            who = r.get("customer") or r.get("email")
            reply = (r.get("reply_draft") or "").strip()
            lines.append(f"- {who} ({r.get('intent')}, score {r.get('score')})" + (f"\n  - draft reply: “{reply}”" if reply else ""))
        lines.append("")
    lines.append("_Generated by lead-qual-agent._")
    return "\n".join(lines)
